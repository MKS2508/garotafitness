package x4

import (
	"testing"

	"github.com/stretchr/testify/require"
)

func TestEncryptFS15Zeros(t *testing.T) {
	t.Parallel()
	key := keys[2] // dataS / FS15-25
	plain := make([]byte, 40)
	got := append([]byte(nil), plain...)
	c := newFarmCipher(key)
	c.encrypt(got)
	want := []byte{
		0x14, 0x51, 0x14, 0x15, 0x55, 0x41, 0x41, 0x10,
		0x38, 0xf4, 0x92, 0xa2, 0x7f, 0x9b, 0xb8, 0x43,
		0x39, 0xf7, 0x29, 0x7f, 0xbf, 0x97, 0x97, 0x34,
		0x69, 0x67, 0xfc, 0x76, 0x1f, 0x55, 0x18, 0x00,
		0x33, 0xbf, 0x03, 0xab, 0x6f, 0x3f, 0x3b, 0x3d,
	}
	require.Equal(t, want, got)
	c2 := newFarmCipher(key)
	c2.decrypt(got)
	require.Equal(t, plain, got)
}

func TestEncryptFS13BFirstEntry(t *testing.T) {
	t.Parallel()
	key := keys[1] // DLC 02 01
	plain := []byte{
		0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x58, 0x0d, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x52, 0x0d, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	}
	want := []byte{
		0x15, 0x45, 0x14, 0x10, 0x50, 0x11, 0x45, 0x04,
		0x09, 0xef, 0x6b, 0xd0, 0x3d, 0xb4, 0xcd, 0x91,
		0xc9, 0x99, 0x39, 0x2b, 0xe0, 0x53, 0x0b, 0x45,
	}
	got := append([]byte(nil), plain...)
	c := newFarmCipher(key)
	c.encrypt(got)
	require.Equal(t, want, got)
	c2 := newFarmCipher(key)
	c2.decrypt(got)
	require.Equal(t, plain, got)
}
