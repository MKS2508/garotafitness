// CDF table initializers + non-uniform frequency tables for the magic2
// rANS decoder. Uniform-prior seeders (init_nibble, init_sym8) plus the
// struct Hist layout come from garotafitness-fork
// stream/magic2/guest/main.cpp:663-674. The non-uniform per-symbol CDF
// targets (kNibbleTgt, kMatchTgt, kSym8Tgt, kOff8Tgt, kHdrTgt, kLen8Tgt)
// plus the per-stream helper tables (kEsiTab, kMixTab, kHistTab, kPcMask)
// are direct byte-for-byte ports of main.cpp:25-209.
//
// Used by the cls-magic2 v22 decoder to seed CDF rows (hiA, hiB, loA, loB,
// clsTab, lenTab, off8a, off8b, …) before any adaptive updates land.
package godec

// Sym8 is an 8-slot cumulative distribution table (CDF) used by 8-symbol
// rANS decoders. The 8 cumulative slots must sum to the rANS slot window
// (2^15 here); init_sym8 seeds them uniformly with step 0x1000.
//
// Mirrors the uint16_t[8] slices in main.cpp that init_sym8 populates
// (lenTab, off8a, off8b in decode_v22 at line 1062-1065).
type Sym8 [8]uint16

// Nibble16 is a 16-slot CDF used by 16-symbol rANS decoders. The 16
// cumulative slots must sum to the rANS slot window (2^15 here);
// init_nibble seeds them uniformly with step 0x800.
//
// Mirrors the uint16_t[16] slices in main.cpp that init_nibble populates
// (hiA, hiB, loA, loB, clsTab, off2A, off2B, off3A, off3B, off11A, …).
type Nibble16 [16]uint16

// Hist mirrors struct Hist in main.cpp:670-674 — eight packed uint32
// counters at offsets 0x08, 0x0c, 0x10, 0x14, 0x18, 0x1c, 0x20, 0x24,
// consumed by hist_h1 / hist_row during cls-magic2 boundary detection.
// In the PE this struct sits inline in a 0x20-byte window of the per-stream
// state; here it is a standalone value the caller threads through.
//
// The W-prefixed field names encode the byte offsets the cls-magic2 PE
// reads at (W08 = 0x08, W0C = 0x0c, …). The semantic role of each slot
// (per-bit cumulative, per-symbol weight, etc.) lives in the cls-magic2
// binary; this package only preserves the layout.
type Hist struct {
	W08 uint32
	W0C uint32
	W10 uint32
	W14 uint32
	W18 uint32
	W1C uint32
	W20 uint32
	W24 uint32
}

// init_nibble populates the first 16 slots of d with the uniform CDF
// d[i] = i * 0x800. main.cpp:663-666. Step 0x800 = 2^11, range 16 * 0x800
// = 0x8000 = 2^15 — exactly the rANS slot window consumed by get_nibble
// with kNibbleTgt and the 16-symbol tables of decode_v22.
//
// Caller must ensure len(d) >= 16. Out-of-bounds slots are not touched.
func init_nibble(d []uint16) {
	for i := 0; i < 16; i++ {
		d[i] = uint16(i) * 0x800
	}
}

// init_sym8 populates the first 8 slots of d with the uniform CDF
// d[i] = i * 0x1000. main.cpp:667-670. Step 0x1000 = 2^12, range 8 * 0x1000
// = 0x8000 = 2^15 — the same rANS slot window, just coarser over 8 symbols.
//
// Caller must ensure len(d) >= 8. Out-of-bounds slots are not touched.
func init_sym8(d []uint16) {
	for i := 0; i < 8; i++ {
		d[i] = uint16(i) * 0x1000
	}
}

